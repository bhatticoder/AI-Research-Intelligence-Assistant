# IEEEtran LaTeX Template Builder
# ══════════════════════════════════════════════════════════════════════════════

def build_ieeeetran_latex(
    title: str,
    authors: str,
    abstract: str,
    body_sections: Dict[str, str],
    references: List[Dict],
    journal: str = "IEEE Transactions",
) -> tuple[str, str]:
    """
    Build a complete IEEEtran-formatted .tex file and .bib bibliography.

    Args:
        title: Paper title.
        authors: Author line string.
        abstract: Abstract paragraph text.
        body_sections: OrderedDict of {section_title: section_body_latex}.
        references: List of {key, author, title, journal, year, volume, pages} dicts.
        journal: Target journal name (used in a comment only).

    Returns:
        Tuple of (main_tex_content, bibliography_bib_content).
    """
    now = datetime.now().strftime("%B %Y")

    # ── Build body ─────────────────────────────────────────────────────────
    body_parts = []
    roman = ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X"]
    for i, (sec_title, sec_body) in enumerate(body_sections.items()):
        r = roman[i] if i < len(roman) else str(i + 1)
        body_parts.append(f"\\section{{{sec_title}}}")
        body_parts.append(sec_body.strip())

    body_latex = "\n\n".join(body_parts)

    # ── Build bibliography ──────────────────────────────────────────────────
    bib_entries = []
    for ref in references:
        key = ref.get("key", f"ref{ref.get('n', 1)}")
        author = ref.get("author", "Author, A.")
        title = ref.get("title", "Untitled")
        journal_name = ref.get("journal", "IEEE Transactions")
        year = ref.get("year", str(datetime.now().year))
        volume = ref.get("volume", "1")
        pages = ref.get("pages", "1--10")
        bib_entries.append(
            f"@article{{{key},\n"
            f"  author  = {{{author}}},\n"
            f"  title   = {{{{{title}}}}},\n"
            f"  journal = {{{journal_name}}},\n"
            f"  year    = {{{year}}},\n"
            f"  volume  = {{{volume}}},\n"
            f"  pages   = {{{pages}}}\n"
            f"}}"
        )

    bib_content = "\n\n".join(bib_entries) if bib_entries else (
        "@article{placeholder,\n"
        "  author  = {Author, A.},\n"
        "  title   = {{Placeholder Reference}},\n"
        "  journal = {IEEE Transactions},\n"
        "  year    = {2024}\n"
        "}"
    )

    # ── Build cite commands for the references section ──────────────────────
    cite_keys = [ref.get("key", f"ref{ref.get('n', i+1)}") for i, ref in enumerate(references)]

    tex_content = r"""\documentclass[journal]{IEEEtran}

%% ── Core Packages ──────────────────────────────────────────────
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage{amsmath,amssymb,amsfonts}
\usepackage{algorithmic}
\usepackage{array}
\usepackage{textcomp}
\usepackage{booktabs}
\usepackage{graphicx}
\usepackage{xcolor}
\usepackage{hyperref}
\usepackage{url}
\usepackage{cite}
\usepackage{tikz}
\usepackage{pgfplots}
\pgfplotsset{compat=1.18}

%% ── Metadata ────────────────────────────────────────────────────
%% Target Journal: """ + journal + r"""
%% Generated by ARIA v2.0 — """ + now + r"""

\begin{document}

\title{""" + _latex_escape(title) + r"""}

\author{""" + _latex_escape(authors) + r"""\thanks{Generated by ARIA v2.0 — AI Research \& Intelligence Assistant. Local LLM synthesis from researcher-provided literature.}}

\maketitle

\begin{abstract}
""" + abstract.strip() + r"""
\end{abstract}

\begin{IEEEkeywords}
machine learning, natural language processing, retrieval-augmented generation, IEEE research automation, local LLM
\end{IEEEkeywords}

""" + body_latex + r"""

\bibliographystyle{IEEEtran}
\bibliography{references}

\end{document}
"""

    return tex_content, bib_content


def _latex_escape(text: str) -> str:
    """Escape special LaTeX characters in plain text strings."""
    replacements = [
        ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
        ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"),
        ("^", r"\textasciicircum{}"),
    ]
    for char, escaped in replacements:
        text = text.replace(char, escaped)
    return text


