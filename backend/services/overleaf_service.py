"""
ARIA Overleaf Integration Service  v1.0
========================================
Integrates pyoverleaf to push generated research papers directly to Overleaf.

Architecture:
  - Authenticates via browser cookies (Chrome/Firefox) — no password required.
  - Creates a new Overleaf project via Overleaf's internal REST API.
  - Uploads the LaTeX .tex file + bibliography .bib via pyoverleaf.
  - Returns the project URL for the Obsidian plugin to display as a clickable link.
  - Lists and deletes ARIA-generated Overleaf projects.

Requirements:
  pip install pyoverleaf websocket-client browser-cookie3 beautifulsoup4

Author: ARIA Backend — Overleaf Integration
"""

import logging
import io
import json
import re
import time
from datetime import datetime
from typing import Optional, List, Dict, Any

logger = logging.getLogger(__name__)

# ── Lazy import guard for optional pyoverleaf dep ─────────────────────────────
try:
    import pyoverleaf
    from pyoverleaf import Api as OverleafApi
    _PYOVERLEAF_AVAILABLE = True
except ImportError:
    _PYOVERLEAF_AVAILABLE = False
    logger.warning(
        "[Overleaf] pyoverleaf not installed. "
        "Run: pip install pyoverleaf websocket-client browser-cookie3"
    )

# ── ARIA project tag written into Overleaf project name prefix ────────────────
_ARIA_TAG = "[ARIA]"
_OVERLEAF_HOST = "www.overleaf.com"


